import numpy as np  # type: ignore
import ROOT  # type: ignore


def load_wcsim_library() -> None:
    """
    Load the WCSim ROOT dictionary.

    This requires that the WCSim environment has already been sourced,
    e.g. this_wcsim.sh or the corresponding container setup script.
    """
    status = ROOT.gSystem.Load("libWCSimRoot.so")

    if status < 0:
        raise RuntimeError(
            "Could not load libWCSimRoot.so. "
            "Make sure the WCSim environment is sourced inside the container."
        )


def print_track(trigger):
    """
    Print information about the tracks in a trigger.
    """
    for i_track in range(trigger.GetNtrack()):
        trk = trigger.GetTracks().At(i_track)

        print(
            "PDG:",
            trk.GetIpnu(),
            "parent type:",
            trk.GetParenttype(),
            "ID:",
            trk.GetId(),
            "parent ID:",
            trk.GetParentId(),
            "creator:",
            trk.GetCreatorProcessName(),
            "start:",
            [trk.GetStart(i) for i in range(3)],
            "stop:",
            [trk.GetStop(i) for i in range(3)],
        )


def print_trigger(event):
    n_triggers = event.GetNumberOfEvents()

    for i_trigger in range(n_triggers):
        trigger = event.GetTrigger(i_trigger)

        print(
            "trigger:",
            i_trigger,
            "type:",
            trigger.GetTriggerType(),
            "info:",
            list(trigger.GetTriggerInfo()),
            "ndigi:",
            trigger.GetNcherenkovdigihits(),
            "nraw:",
            trigger.GetNcherenkovhits(),
            "sumQ:",
            trigger.GetSumQ(),
        )


def trigger_info(input_file, entries):
    load_wcsim_library()
    input_file = ROOT.TFile.Open(str(input_file))
    tree = input_file.Get("wcsimT")
    event = ROOT.WCSimRootEvent()
    tree.SetBranchAddress("wcsimrootevent", ROOT.AddressOf(event))
    for i_event in list(entries):
        tree.GetEntry(i_event - 1)
        print_trigger(event)


def track_info(input_file, entries):
    load_wcsim_library()
    input_file = ROOT.TFile.Open(str(input_file))
    tree = input_file.Get("wcsimT")
    event = ROOT.WCSimRootEvent()
    tree.SetBranchAddress("wcsimrootevent", ROOT.AddressOf(event))
    for i_event in list(entries):
        tree.GetEntry(i_event - 1)
        for i_trigger in range(event.GetNumberOfEvents()):
            trigger = event.GetTrigger(i_trigger)
            print_track(trigger)


def check_muon_containment(input_file, entries):
    load_wcsim_library()

    input_file = ROOT.TFile.Open(str(input_file))
    tree = input_file.Get("wcsimT")

    event = ROOT.WCSimRootEvent()
    tree.SetBranchAddress("wcsimrootevent", ROOT.AddressOf(event))

    id_radius = 3240.0
    id_half_height = 3290.0

    contained_events = []
    non_contained_events = []
    missing_muon_events = []

    for i_event in entries:
        tree.GetEntry(i_event - 1)

        trigger = event.GetTrigger(0)
        tracks = trigger.GetTracks()

        muon_track = None

        for i_track in range(trigger.GetNtrack()):
            track = tracks.At(i_track)

            if (
                abs(int(track.GetIpnu())) == 13
                and int(track.GetParenttype()) == 0
                and int(track.GetId()) > 0
            ):
                muon_track = track
                break

        if muon_track is None:
            missing_muon_events.append(i_event)
            continue

        stop = np.array(
            [
                float(muon_track.GetStop(0)),
                float(muon_track.GetStop(1)),
                float(muon_track.GetStop(2)),
            ]
        )

        r_stop = np.hypot(stop[0], stop[1])

        is_contained = r_stop < id_radius and abs(stop[2]) < id_half_height

        if is_contained:
            contained_events.append((i_event, stop))
        else:
            non_contained_events.append((i_event, stop))

    print(f"Contained muons: {len(contained_events)} out of {len(entries)}.")

    print(f"Non-contained muons: {len(non_contained_events)} out of {len(entries)}.")

    print(f"Events with no primary muon: {len(missing_muon_events)}.")

    if contained_events:
        print("\nUnexpected contained events:")
        for i_event, stop in contained_events:
            print(f"Event {i_event}: stop = {stop}")

    return contained_events, non_contained_events, missing_muon_events


